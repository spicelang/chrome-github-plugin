#!/usr/bin/env node
/**
 * Regenerates extension/shared/linguist-data.js from the upstream GitHub Linguist data files:
 * - language colors (languages.yml)
 * - vendored path patterns (vendor.yml)
 * - documentation path patterns (documentation.yml)
 *
 * Usage: node scripts/update-linguist-data.mjs [linguist git ref, default: main]
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ref = process.argv[2] || 'main';
const base = `https://raw.githubusercontent.com/github-linguist/linguist/${ref}/lib/linguist`;

async function fetchText(name) {
  const res = await fetch(`${base}/${name}`);
  if (!res.ok) throw new Error(`Failed to fetch ${name}: ${res.status}`);
  return res.text();
}

// languages.yml is a flat map of language names to properties. We only need the top-level keys, their colors and
// aliases, so a tiny line-based parser is sufficient and avoids a YAML dependency.
function parseLanguages(yml) {
  const colors = {};
  const aliases = {};
  let current = null;
  let inAliases = false;
  for (const line of yml.split('\n')) {
    const top = /^("?)(.+?)\1:\s*$/.exec(line);
    if (top && !line.startsWith(' ') && !line.startsWith('#')) {
      current = top[2].replace(/\\"/g, '"');
      aliases[current.toLowerCase()] = current;
      inAliases = false;
      continue;
    }
    if (!current) continue;
    const color = /^ {2}color:\s*"(#[0-9a-fA-F]{6})"/.exec(line);
    if (color) colors[current] = color[1].toLowerCase();
    if (/^ {2}[^\s-]/.test(line)) inAliases = /^ {2}aliases:/.test(line);
    const alias = /^ {2}- (.+)$/.exec(line);
    if (inAliases && alias) aliases[alias[1].trim().replace(/^"|"$/g, '').toLowerCase()] = current;
  }
  return { colors, aliases };
}

// vendor.yml and documentation.yml are lists of single-quoted or plain Ruby regexes
function parsePatterns(yml) {
  const patterns = [];
  for (const line of yml.split('\n')) {
    const m = /^- (.+)$/.exec(line);
    if (!m) continue;
    let p = m[1].trim();
    if (p.startsWith("'") && p.endsWith("'")) p = p.slice(1, -1).replace(/''/g, "'");
    else if (p.startsWith('"') && p.endsWith('"')) p = JSON.parse(p);
    // Ruby inline flags like (?i) are not supported by JS, translate them to the case-insensitive flag
    let flags = '';
    if (p.includes('(?i)')) {
      p = p.replace(/\(\?i\)/g, '');
      flags = 'i';
    }
    try {
      new RegExp(p, flags);
      patterns.push([p, flags]);
    } catch (e) {
      console.warn(`Skipping pattern not supported by JS: ${p}`);
    }
  }
  return patterns;
}

const [languages, vendor, documentation] = await Promise.all(
  ['languages.yml', 'vendor.yml', 'documentation.yml'].map(fetchText),
);
const { colors, aliases } = parseLanguages(languages);
const data = {
  colors,
  aliases,
  vendor: parsePatterns(vendor),
  documentation: parsePatterns(documentation),
};

const out = `// Generated by scripts/update-linguist-data.mjs from github-linguist/linguist@${ref}. Do not edit by hand.
(function (root) {
  'use strict';
  const data = ${JSON.stringify(data)};
  if (typeof module === 'object' && module.exports) module.exports = data;
  else (root.SpiceGH = root.SpiceGH || {}).linguistData = data;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'extension', 'shared', 'linguist-data.js');
writeFileSync(target, out);
console.log(
  `Wrote ${target}: ${Object.keys(data.colors).length} colors, ${data.vendor.length} vendor patterns, ` +
    `${data.documentation.length} documentation patterns`,
);
